def test_audit_feature_names_no_target_leakage():
    """Verify FEATURE_NAMES does not contain ground truth labels, targets, or reference values."""
    forbidden = {
        "ground_truth_fault_label",
        "reference_pressure_mmhg",
        "reference_force_n",
        "reference_flow_ml_h",
        "operating_state",
        "target",
        "error",
        "label",
    }
    for feat in FEATURE_NAMES:
        assert feat.lower() not in forbidden, f"Leaked target column found in features: {feat}"


def test_audit_feature_pipeline_temporal_causality(pipeline):
    """Verify that altering future samples does NOT affect past feature values (strict backward causality)."""
    n = 100
    p1 = np.full(n, 80.0)
    df1 = pd.DataFrame({"sensor_pressure_mmhg": p1})
    feats1 = pipeline.transform_dataframe(df1)

    # Modify only the last 20 steps (steps 80 to 99)
    p2 = p1.copy()
    p2[80:] = 250.0  # Future shock
    df2 = pd.DataFrame({"sensor_pressure_mmhg": p2})
    feats2 = pipeline.transform_dataframe(df2)

    # Prior steps (0 to 79) must be 100% identical
    for col in FEATURE_NAMES:
        np.testing.assert_allclose(
            feats1[col].iloc[:80].values,
            feats2[col].iloc[:80].values,
            err_msg=f"Feature {col} leaked future information into past steps!",
        )


