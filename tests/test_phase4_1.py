def test_audit_classifier_extreme_drift(pipeline, classifier):
    """Verify classifier correctly recognizes aggressive drift (120 mmHg/h) without breaking."""
    cfg = SimulatorConfig(duration_seconds=900, random_seed=701)
    df_run = generate_infusion_run(
        scenario=FaultClass.POSITIVE_DRIFT,
        config=cfg,
        fault_start_sec=300,
        drift_rate_mmhg_per_hour=120.0,
    )
    feats = pipeline.transform_dataframe(df_run)
    pred_class = classifier.predict(feats.iloc[[-1]])[0]
    # Class 1 is POSITIVE_DRIFT, or it may transition to sudden offset / fault
    assert pred_class in (1, 3), f"Aggressive drift classified as unexpected class: {pred_class}"


def test_audit_classifier_subtle_drift_behavior(pipeline, classifier):
    """Verify behavior on subtle drift (6 mmHg/h).

    At subtle rates, early drift resembles normal noise until sufficient deviation accumulates.
    """
    cfg = SimulatorConfig(duration_seconds=900, random_seed=702)
    df_run = generate_infusion_run(
        scenario=FaultClass.POSITIVE_DRIFT,
        config=cfg,
        fault_start_sec=300,
        drift_rate_mmhg_per_hour=6.0,
    )
    feats = pipeline.transform_dataframe(df_run)
    probas = classifier.predict_proba(feats.iloc[[-1]])[0]
    # Should predict either POSITIVE_DRIFT or NORMAL (due to small signal-to-noise ratio)
    top_pred = np.argmax(probas)
    assert top_pred in (0, 1), f"Subtle drift classified as unexpected class {top_pred}"


