# ---------------------------------------------------------------------------

def test_audit_sensor_health_occlusion_decoupling():
    """Verify that occlusion surges process risk to CRITICAL while preserving sensor health."""
    engine = CrossSensorConsistencyEngine(pressure_occlusion_threshold_mmhg=250.0)
    health_engine = SensorHealthEngine()

    cfg = SimulatorConfig(duration_seconds=600, random_seed=706)
    df_run = generate_infusion_run(
        scenario=FaultClass.GENUINE_DOWNSTREAM_OCCLUSION,
        config=cfg,
        fault_start_sec=150,
        occlusion_time_constant_sec=70.0,
    )
    assessment = engine.assess_run(df_run)
    assert assessment.verdict == ConsistencyVerdict.GENUINE_OCCLUSION_CONFIRMED

    report = health_engine.evaluate_health(
        sensor_id="PRESS_01",
        sensor_type="pressure",
        consistency_assessment=assessment,
        anomaly_detected=True,
        anomaly_severity=0.88,
    )

    # Transducer integrity must remain healthy
    assert report.sensor_health_score >= 90.0
    # Process risk must escalate to CRITICAL
    assert report.process_risk_score >= 90.0
    assert report.process_risk_level == "CRITICAL"
    assert "fluid_pathway_occlusion" in report.process_risk_factors


def test_audit_sensor_drift_affects_health_not_occlusion():
    """Verify gradual drift degrades sensor health score while process risk remains low."""
    engine = CrossSensorConsistencyEngine()
    health_engine = SensorHealthEngine()

    cfg = SimulatorConfig(duration_seconds=600, random_seed=707)
    df_run = generate_infusion_run(
        scenario=FaultClass.POSITIVE_DRIFT,
        config=cfg,
        fault_start_sec=100,
        drift_rate_mmhg_per_hour=120.0,
    )
    assessment = engine.assess_run(df_run, ewma_alarm_active=True)
    assert assessment.verdict == ConsistencyVerdict.SENSOR_DRIFT_SUSPECTED

    report = health_engine.evaluate_health(
        sensor_id="PRESS_01",
        sensor_type="pressure",
        consistency_assessment=assessment,
        ewma_drift_detected=True,
    )

    # Sensor health should drop due to drift
    assert report.sensor_health_score <= 85.0
    # Process delivery risk is not CRITICAL (occlusion is CRITICAL, drift is dosing inaccuracy risk)
    assert report.process_risk_level in ("MODERATE", "HIGH")
    assert report.process_risk_level != "CRITICAL"
    assert report.process_risk_score <= 60.0


